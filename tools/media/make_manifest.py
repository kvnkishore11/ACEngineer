#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""Regenerate media/MANIFEST.md.

The ~22 GB under media/ is deliberately not tracked by git (see
docs/adr/0002-media-is-ignored-not-tracked.md). This manifest is what keeps the
ignored tree auditable: every file's path, size and SHA-256, so a missing or
corrupted video is detectable without committing the bytes.

    uv run tools/media/make_manifest.py            # rewrite media/MANIFEST.md
    uv run tools/media/make_manifest.py --check     # verify, exit 1 on drift

Safe to re-run; the output is deterministic (entries sorted by path).
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MEDIA = REPO_ROOT / "media"
MANIFEST = MEDIA / "MANIFEST.md"

# Files that describe the tree rather than being part of it.
EXCLUDE_NAMES = {"MANIFEST.md", ".DS_Store"}


def iter_media_files() -> list[Path]:
    files = [
        p
        for p in MEDIA.rglob("*")
        if p.is_file() and not p.is_symlink() and p.name not in EXCLUDE_NAMES
    ]
    return sorted(files, key=lambda p: str(p.relative_to(REPO_ROOT)))


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def human(n: int) -> str:
    size = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if size < 1024 or unit == "TB":
            return f"{size:.1f} {unit}" if unit != "B" else f"{int(size)} B"
        size /= 1024
    raise AssertionError("unreachable: the TB branch always returns")


ROW_RE = re.compile(r"^\| `([^`]+)` \| [^|]+ \| `([0-9a-f]{64})` \|$")


def parse_manifest(text: str) -> dict[str, str]:
    """Read a rendered manifest back into {repo-relative path: sha256}.

    Only the hash is parsed back. Size is rendered human-readable and the hash
    pins the content anyway, so comparing sizes would add nothing.
    """
    out: dict[str, str] = {}
    for line in text.splitlines():
        m = ROW_RE.match(line.strip())
        if m:
            rel, digest = m.groups()
            out[rel] = digest
    return out


def render(files: list[Path]) -> str:
    lines = [
        "# `media/` manifest",
        "",
        "Generated by `uv run tools/media/make_manifest.py` — do not edit by hand.",
        "",
        "The bytes under `media/` are not tracked by git. This file is the tracked,",
        "auditable record of what should be there: path, size and SHA-256 for every",
        "file. Verify a checkout with `uv run tools/media/make_manifest.py --check`.",
        "",
    ]
    total = sum(p.stat().st_size for p in files)
    lines += [
        f"- Files: {len(files)}",
        f"- Total size: {human(total)}",
        "",
        "| Path | Size | SHA-256 |",
        "|---|---:|---|",
    ]
    for p in files:
        rel = p.relative_to(REPO_ROOT)
        lines.append(f"| `{rel}` | {human(p.stat().st_size)} | `{sha256(p)}` |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the manifest matches the tree; exit 1 on drift",
    )
    args = ap.parse_args()

    if not MEDIA.is_dir():
        print(f"error: {MEDIA} does not exist", file=sys.stderr)
        return 1

    files = iter_media_files()

    if args.check:
        if not MANIFEST.exists():
            print(f"error: {MANIFEST} is missing", file=sys.stderr)
            return 1
        expected = parse_manifest(MANIFEST.read_text())
        actual = {str(p.relative_to(REPO_ROOT)) for p in files}

        missing = sorted(set(expected) - actual)
        extra = sorted(actual - set(expected))
        if not actual:
            # A fresh clone has no media at all: the bytes are gitignored. Say
            # so plainly rather than "no files found", but still fail — the
            # checkout genuinely does not match the manifest.
            print(
                f"media/ contains no files; the manifest lists {len(expected)}. "
                "The bytes are gitignored, so a fresh clone starts empty — "
                "fetch the media before auditing it.",
                file=sys.stderr,
            )
            return 1

        changed = [
            rel
            for rel in sorted(set(expected) & actual)
            if expected[rel] != sha256(REPO_ROOT / rel)
        ]

        if missing or extra or changed:
            print(
                f"error: media/MANIFEST.md does not match the tree "
                f"({len(missing)} missing, {len(extra)} unlisted, {len(changed)} changed)",
                file=sys.stderr,
            )
            for rel in missing[:20]:
                print(f"  missing:  {rel}", file=sys.stderr)
            for rel in extra[:20]:
                print(f"  unlisted: {rel}", file=sys.stderr)
            for rel in changed[:20]:
                print(f"  changed:  {rel}", file=sys.stderr)
            if len(missing) + len(extra) + len(changed) > 60:
                print("  ... (truncated)", file=sys.stderr)
            print(
                "\nRe-run `uv run tools/media/make_manifest.py` if the tree is correct.",
                file=sys.stderr,
            )
            return 1
        print(f"media/MANIFEST.md matches the tree ({len(files)} files)")
        return 0

    if not files:
        print(
            f"error: no files found under {MEDIA} — refusing to overwrite the "
            "manifest with an empty one",
            file=sys.stderr,
        )
        return 1

    rendered = render(files)

    MANIFEST.write_text(rendered)
    print(f"wrote {MANIFEST.relative_to(REPO_ROOT)} ({len(files)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
