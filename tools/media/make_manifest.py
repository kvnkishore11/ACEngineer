#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///
"""Regenerate media/MANIFEST.md.

The ~22 GB under media/ is deliberately not tracked by git (see
docs/adr/0002-media-is-ignored-not-tracked.md). This manifest is what keeps the
ignored tree auditable: every file's path, size and SHA-256, so a missing or
corrupted video is detectable without committing the bytes.

    uv run tools/media/make_manifest.py            # rewrite media/MANIFEST.md
    uv run tools/media/make_manifest.py --check     # verify, exit 1 on drift

Safe to re-run; the output is deterministic (entries sorted by path).
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
MEDIA = REPO_ROOT / "media"
MANIFEST = MEDIA / "MANIFEST.md"

# Files that describe the tree rather than being part of it.
EXCLUDE_NAMES = {"MANIFEST.md", ".DS_Store"}


def iter_media_files() -> list[Path]:
    files = [
        p
        for p in MEDIA.rglob("*")
        if p.is_file() and not p.is_symlink() and p.name not in EXCLUDE_NAMES
    ]
    return sorted(files, key=lambda p: str(p.relative_to(REPO_ROOT)))


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def human(n: int) -> str:
    size = float(n)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if size < 1024 or unit == "TB":
            return f"{size:.1f} {unit}" if unit != "B" else f"{int(size)} B"
        size /= 1024
    return f"{size:.1f} TB"


def render(files: list[Path]) -> str:
    lines = [
        "# `media/` manifest",
        "",
        "Generated by `uv run tools/media/make_manifest.py` — do not edit by hand.",
        "",
        "The bytes under `media/` are not tracked by git. This file is the tracked,",
        "auditable record of what should be there: path, size and SHA-256 for every",
        "file. Verify a checkout with `uv run tools/media/make_manifest.py --check`.",
        "",
    ]
    total = sum(p.stat().st_size for p in files)
    lines += [
        f"- Files: {len(files)}",
        f"- Total size: {human(total)}",
        "",
        "| Path | Size | SHA-256 |",
        "|---|---:|---|",
    ]
    for p in files:
        rel = p.relative_to(REPO_ROOT)
        lines.append(f"| `{rel}` | {human(p.stat().st_size)} | `{sha256(p)}` |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--check",
        action="store_true",
        help="verify the manifest matches the tree; exit 1 on drift",
    )
    args = ap.parse_args()

    if not MEDIA.is_dir():
        print(f"error: {MEDIA} does not exist", file=sys.stderr)
        return 1

    files = iter_media_files()
    if not files:
        print(f"error: no files found under {MEDIA}", file=sys.stderr)
        return 1

    rendered = render(files)

    if args.check:
        if not MANIFEST.exists():
            print(f"error: {MANIFEST} is missing", file=sys.stderr)
            return 1
        if MANIFEST.read_text() != rendered:
            print(
                "error: media/MANIFEST.md is out of date — "
                "re-run `uv run tools/media/make_manifest.py`",
                file=sys.stderr,
            )
            return 1
        print(f"media/MANIFEST.md matches the tree ({len(files)} files)")
        return 0

    MANIFEST.write_text(rendered)
    print(f"wrote {MANIFEST.relative_to(REPO_ROOT)} ({len(files)} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
